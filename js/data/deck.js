// 'related' is 'ru:стол' or 'it:piazza · ru:…' → [{ lang, word }]
const parseRelated = (s) => (s ? s.split(' · ').map((p) => { const [lang, ...w] = p.split(':'); return { lang, word: w.join(':') }; }) : []);

export function parseDeck(row, i) {
  const [lemma, en, ex, exEn, level, related] = row.split('|');
  const m = ex.match(/\*([^*]+)\*/);
  return { i, lemma, en, ex: ex.replace(/\*/g, ''), cloze: ex.replace(/\*[^*]+\*/, '_____'), answer: m ? m[1] : lemma, exEn, level, related: parseRelated(related) };
}
export const DECK_ITEMS = DECK.map(parseDeck);
